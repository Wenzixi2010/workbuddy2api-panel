/**
 * CodeBuddy 品牌标记。
 *
 * 两套形态：
 *  - `color`（默认）：官方彩色版——青紫径向渐变的圆角方块 + 白色字形。
 *    渐变是品牌资产的一部分，不能改成 currentColor，否则就不是那个 logo 了。
 *    **深色主题下不能反色**：底色本身够深、字形是白的，反色会在深底上糊成一片。
 *  - `mono`：单色版（currentColor），用于需要跟随文字色的小尺寸场合。
 *
 * 渐变 id 必须唯一：同一页面上顶栏和登录页可能同时渲染两个实例，
 * 复用同一个 id 会让后挂载的那个引用到先卸载的 defs，出现图标变透明。
 * 所以用 useId() 生成实例级唯一 id。
 *
 * 路径来自官方图标集（@lobehub/icons-static-svg / codebuddy-color.svg）。
 */
import { useId } from 'react'

type Props = {
  /** 渲染尺寸（px），宽高一致。 */
  size?: number
  /** 彩色（官方）或单色（跟随 currentColor）。 */
  variant?: 'color' | 'mono'
  className?: string
}

export default function CodebuddyMark({ size = 20, variant = 'color', className }: Props) {
  // useId 返回形如 ":r1:"，冒号在 SVG 的 url(#...) 里是合法的，但为稳妥起见
  // 把非字母数字替换掉，避免个别浏览器/工具链的解析差异。
  const raw = useId()
  const gid = 'cb-grad-' + raw.replace(/[^a-zA-Z0-9]/g, '')
  const clipId = 'cb-clip-' + raw.replace(/[^a-zA-Z0-9]/g, '')

  if (variant === 'mono') {
    return (
      <svg
        viewBox="0 0 24 24"
        width={size}
        height={size}
        fill="currentColor"
        fillRule="evenodd"
        className={className}
        aria-hidden
        focusable="false"
      >
        <path d="M18.777 1.647c.28-.02.536.114.972.51 1.018.926 2.437 2.828 3.318 4.452l.34.631.482.24.11.06v3.638a5.206 5.206 0 00-5.32-1.23c-.491.166-1.021.471-2.08 1.082l-6.09 3.516c-1.057.61-1.586.916-1.975 1.259a5.208 5.208 0 00-1.493 5.572c.165.49.471 1.02 1.082 2.08l.315.543h-3.26c-.685 0-1.34-.135-1.939-.377-.169-.956-.009-1.789.469-2.335.158-.18.164-.189.13-.493a11.846 11.846 0 01-.057-1.711l.02-.444-.667-1.18C2.1 15.622 1.445 14.078 1.192 12.9c-.133-.647-.125-.934.04-1.146.1-.128.427-.261.822-.334.994-.175 3.162-.017 5.575.41l.25.043.551-.487c.915-.81 1.522-1.264 2.641-1.962 1.167-.73 2.484-1.331 3.967-1.807l.476-.152.261-.688c.937-2.471 1.896-4.293 2.58-4.9.235-.21.25-.22.422-.23z" />
        <path d="M12.139 18.2a1.203 1.203 0 011.642.44l1.296 2.243a1.204 1.204 0 01-2.083 1.203l-1.296-2.243a1.203 1.203 0 01.44-1.644zM18.629 14.452a1.203 1.203 0 011.642.44l1.295 2.244a1.203 1.203 0 11-2.083 1.203l-1.295-2.243a1.203 1.203 0 01.44-1.644z" />
      </svg>
    )
  }

  return (
    <svg
      viewBox="0 0 24 24"
      width={size}
      height={size}
      className={className}
      aria-hidden
      focusable="false"
    >
      <defs>
        <radialGradient
          id={gid}
          cx="0"
          cy="0"
          r="1"
          gradientUnits="userSpaceOnUse"
          gradientTransform="matrix(-9.00009 -16 16 -9.00009 21 24.5)"
        >
          <stop stopColor="#2EA99D" />
          <stop offset="1" stopColor="#6C4DFF" />
        </radialGradient>
        <clipPath id={clipId}>
          <rect width="24" height="24" rx="5.179" />
        </clipPath>
      </defs>
      <g clipPath={`url(#${clipId})`}>
        <rect width="24" height="24" fill={`url(#${gid})`} />
        <path
          d="M18.777 1.647c.28-.02.536.114.972.51 1.018.926 2.437 2.828 3.318 4.452l.34.631.482.24.11.06v3.638a5.206 5.206 0 00-5.32-1.23c-.491.166-1.021.471-2.08 1.082l-6.09 3.516c-1.057.61-1.586.916-1.975 1.259a5.208 5.208 0 00-1.493 5.572c.165.49.471 1.02 1.082 2.08l.315.543h-3.26c-.685 0-1.34-.135-1.939-.377-.169-.956-.009-1.789.469-2.335.158-.18.164-.189.13-.493a11.846 11.846 0 01-.057-1.711l.02-.444-.667-1.18C2.1 15.622 1.445 14.078 1.192 12.9c-.133-.647-.125-.934.04-1.146.1-.128.427-.261.822-.334.994-.175 3.162-.017 5.575.41l.25.043.551-.487c.915-.81 1.522-1.264 2.641-1.962 1.167-.73 2.484-1.331 3.967-1.807l.476-.152.261-.688c.937-2.471 1.896-4.293 2.58-4.9.235-.21.25-.22.422-.23z"
          fill="#fff"
        />
        <path
          d="M12.139 18.2a1.203 1.203 0 011.642.44l1.296 2.243a1.204 1.204 0 01-2.083 1.203l-1.296-2.243a1.203 1.203 0 01.44-1.644zM18.629 14.452a1.203 1.203 0 011.642.44l1.295 2.244a1.203 1.203 0 11-2.083 1.203l-1.295-2.243a1.203 1.203 0 01.44-1.644z"
          fill="#fff"
        />
      </g>
    </svg>
  )
}
